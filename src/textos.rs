/// Os idiomas que existem (o config.json só aceita estes).
pub const IDIOMAS: [&str; 2] = ["pt", "en"];

fn procurar(tabela: Tabela, chave: &str) -> Option<&'static str> {
    tabela.iter().find(|(k, _)| *k == chave).map(|(_, v)| *v)
}

/// O texto no idioma configurado; na falta dele, o em português.
pub fn t(chave: &str) -> &'static str {
    let tabela = if crate::config::idioma() == "en" {
        EN
    } else {
        PT
    };
    procurar(tabela, chave)
        .or_else(|| procurar(PT, chave))
        .unwrap_or("?")
}

#[cfg(test)]
mod testes {
    use super::*;

    #[test]
    fn os_dois_idiomas_tem_as_mesmas_chaves() {
        let pt: Vec<_> = PT.iter().map(|(k, _)| k).collect();
        let en: Vec<_> = EN.iter().map(|(k, _)| k).collect();
        assert_eq!(pt, en);
    }
}
